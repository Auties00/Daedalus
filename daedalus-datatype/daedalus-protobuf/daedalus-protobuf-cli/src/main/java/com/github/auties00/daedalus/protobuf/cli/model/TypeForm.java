package com.github.auties00.daedalus.protobuf.cli.model;

/**
 * Specifies how a protobuf message or group is represented as a Java type.
 */
public enum TypeForm {
    /**
     * A concrete final class with package private annotated fields, a constructor,
     * and public accessors, which return an {@code Optional} for a field that can
     * be unset.
     */
    CLASS,

    /**
     * A Java record with annotated record components. A field that can be unset is
     * a nullable boxed component, as the accessor of a record component must return
     * the type of the component.
     */
    RECORD,

    /**
     * A Java interface with abstract getter methods annotated
     * with a field annotation, such as {@code @ProtobufMessage.Int32Field}.
     * An implementation class is generated by the annotation processor.
     */
    INTERFACE
}
